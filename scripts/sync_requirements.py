"""Generate role requirements from the pins in pyproject.toml."""

import argparse
from pathlib import Path
import re
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
HEADER = "# Generated by scripts/sync_requirements.py; edit pyproject.toml instead.\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files differ")
    args = parser.parse_args()
    data = tomllib.loads((ROOT / "pyproject.toml").read_text())
    config = data["tool"]["artsy-fartsy"]
    pins = {}
    for pin in data["project"]["dependencies"] + config["tts-dependencies"]:
        match = re.fullmatch(r"([A-Za-z0-9][A-Za-z0-9_.-]*)==([^\s;]+)", pin)
        if not match:
            raise ValueError(f"Expected an exact dependency pin: {pin}")
        name = re.sub(r"[-_.]+", "-", match.group(1)).lower()
        if name in pins:
            raise ValueError(f"Duplicate dependency: {name}")
        pins[name] = pin
    drift = []
    for filename, names in config["roles"].items():
        normalized = [re.sub(r"[-_.]+", "-", name).lower() for name in names]
        if len(normalized) != len(set(normalized)):
            raise ValueError(f"Duplicate role dependency in {filename}")
        content = HEADER + "".join(f"{pins[name]}\n" for name in normalized)
        path = ROOT / filename
        if args.check:
            if not path.exists() or path.read_text() != content:
                drift.append(filename)
        else:
            path.write_text(content)
    if drift:
        print("Requirements out of sync: " + ", ".join(drift), file=sys.stderr)
        print("Run python scripts/sync_requirements.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
